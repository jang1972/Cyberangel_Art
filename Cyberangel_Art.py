def srt_time_to_seconds(srt_time_str):
    """SRT 시간 문자열(HH:MM:SS,ms)을 초 단위 float으로 변환합니다."""
    parts = srt_time_str.replace(',', '.').split(':')
    h = int(parts[0])
    m = int(parts[1])
    
    
    s = float(parts[2])
    return h * 3600 + m * 60 + s

